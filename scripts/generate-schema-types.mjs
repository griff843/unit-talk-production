#!/usr/bin/env node
/**
 * SPRINT-SCHEMA-ENV-GATES-002: Schema Types Generator
 *
 * Generates baseline Supabase types for schema drift detection.
 * In production, this should be replaced with actual Supabase type generation:
 *   npx supabase gen types typescript --project-id <id> > packages/shared-types/src/supabase.ts
 *
 * This script generates a baseline types file that includes all canonical tables
 * to satisfy the schema drift guard in environments without Supabase CLI access.
 *
 * Usage: node scripts/generate-schema-types.mjs
 */

import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';

// Canonical tables from SYSTEM_INVARIANTS.md
const CANONICAL_TABLES = [
  'unified_picks',
  'bridge_outbox',
  'agent_health',
  'prop_settlements',
  'users',
  'raw_props',
  'games',
  'players',
  'closing_snapshots',
  // Additional tables commonly used
  'audit_log',
  'cappers',
  'daily_picks',
  'smart_tickets',
  'teams',
  'user_profiles',
  'ticket_discord_outbox',
  'player_projections',
  'ops_worker_heartbeats',
  'autopilot_decisions',
  'autopilot_policy_config',
  'autopilot_cooldowns',
];

const OUTPUT_PATH = 'packages/shared-types/src/supabase.ts';

function generateTableType(tableName) {
  const pascalCase = tableName
    .split('_')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');

  return `    ${tableName}: {
      Row: ${pascalCase}Row;
      Insert: Partial<${pascalCase}Row>;
      Update: Partial<${pascalCase}Row>;
      Relationships: [];
    };`;
}

function generateRowInterface(tableName) {
  const pascalCase = tableName
    .split('_')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');

  // Generate common fields based on table name patterns
  let fields = `  id: string;
  created_at: string;
  updated_at: string;`;

  // Add table-specific fields
  if (tableName === 'unified_picks') {
    fields += `
  player_name: string | null;
  sport: string | null;
  stat_type: string | null;
  line: number | null;
  odds: number | null;
  direction: string | null;
  capper: string | null;
  tier: string | null;
  posted_to_discord: boolean;
  settlement_status: string | null;
  lifecycle_stage: string | null;
  bet_slip_id: string | null;
  ticket_type: string | null;
  meta: Record<string, unknown> | null;`;
  } else if (tableName === 'bridge_outbox') {
    fields += `
  event_type: string;
  payload: Record<string, unknown>;
  status: string;
  processed_at: string | null;`;
  } else if (tableName === 'agent_health') {
    fields += `
  agent_name: string;
  status: string;
  last_heartbeat: string;
  metadata: Record<string, unknown> | null;`;
  }

  return `interface ${pascalCase}Row {
${fields}
}`;
}

function generateTypes() {
  const timestamp = new Date().toISOString();

  const content = `/**
 * Supabase Database Types
 *
 * AUTO-GENERATED by scripts/generate-schema-types.mjs
 * Generated at: ${timestamp}
 *
 * SPRINT-SCHEMA-ENV-GATES-002: Baseline types for schema drift detection.
 *
 * NOTE: In production with Supabase CLI access, regenerate with:
 *   npx supabase gen types typescript --project-id <id> > packages/shared-types/src/supabase.ts
 */

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

// Row interfaces for each table
${CANONICAL_TABLES.map(generateRowInterface).join('\n\n')}

export interface Database {
  public: {
    Tables: {
${CANONICAL_TABLES.map(generateTableType).join('\n')}
    };
    Views: Record<string, never>;
    Functions: Record<string, never>;
    Enums: Record<string, never>;
    CompositeTypes: Record<string, never>;
  };
}

// Re-export for convenience
export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];
export type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];
export type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];
`;

  return content;
}

function main() {
  const rootDir = process.cwd();
  const outputPath = join(rootDir, OUTPUT_PATH);

  console.log('SCHEMA TYPES GENERATOR');
  console.log(`   Output: ${OUTPUT_PATH}`);
  console.log(`   Tables: ${CANONICAL_TABLES.length}`);
  console.log('');

  // Ensure directory exists
  mkdirSync(dirname(outputPath), { recursive: true });

  // Generate and write types
  const content = generateTypes();
  writeFileSync(outputPath, content, 'utf-8');

  console.log('Generated types for tables:');
  CANONICAL_TABLES.forEach(t => console.log(`   - ${t}`));
  console.log('');
  console.log('SUCCESS: Schema types generated');
  console.log(`   File: ${OUTPUT_PATH}`);
}

main();
